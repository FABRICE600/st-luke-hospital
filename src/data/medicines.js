export function getMedicinesByCategory(category) {
  if (!category || category === 'all') return medicines
  return medicines.filter((medicine) => medicine.category === category)
}

export function stockLevel(medicine) {
  if (medicine.stock <= 0) return 'out'
  if (medicine.stock <= medicine.reorderLevel) return 'low'
  return 'ok'
}

export function lowStockMedicines(list = medicines) {
  return list.filter((medicine) => stockLevel(medicine) !== 'ok')
}

export function inventoryValue(list = medicines) {
  return list.reduce((total, medicine) => total + medicine.stock * medicine.price, 0)
}