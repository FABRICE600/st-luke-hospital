export function getPatientById(id) {
  return patients.find((patient) => patient.id === id)
}

export function filterPatientsByStatus(list, status) {
  if (!status || status === 'all') return list
  return list.filter((patient) => patient.status === status)
}

export function getPatientInvoices(id) {
  const patient = getPatientById(id)
  return patient ? patient.invoices : []
}

export function patientInvoiceTotals(id) {
  const invoices = getPatientInvoices(id)
  return invoices.reduce(
    (totals, invoice) => {
      totals.total += invoice.amount
      if (invoice.status === 'Paid') totals.paid += invoice.amount
      else totals.pending += invoice.amount
      return totals
    },
    { total: 0, paid: 0, pending: 0 },
  )
}

export function allInvoices() {
  return patients.flatMap((patient) =>
    patient.invoices.map((invoice) => ({
      ...invoice,
      patientId: patient.id,
      patientName: patient.name,
      department: patient.department,
      insurance: patient.insurance,
    })),
  )
}

export function countByStatus() {
  return patients.reduce((counts, patient) => {
    counts[patient.status] = (counts[patient.status] ?? 0) + 1
    return counts
  }, { admitted: 0, discharged: 0, outpatient: 0 })
}